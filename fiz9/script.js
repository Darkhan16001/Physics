function diagram(type,option=0){
  const b="#087dcc",r="#d63a50",g="#16874e",k="#38576e";

  const txt=(x,y,s,c=k,size=18)=>
    `<text x="${x}" y="${y}" text-anchor="middle"
      font-size="${size}" font-weight="600" fill="${c}">${s}</text>`;

  const rect=(x,y,w,h,c)=>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}"
      rx="12" fill="${c}"/>`;

  const arrow=(x,y,X,Y,c=b)=>{
    const a=Math.atan2(Y-y,X-x);
    return `<path d="M${x} ${y} L${X} ${Y}
      L${X-9*Math.cos(a-.5)} ${Y-9*Math.sin(a-.5)}
      M${X} ${Y}
      L${X-9*Math.cos(a+.5)} ${Y-9*Math.sin(a+.5)}"
      stroke="${c}" stroke-width="3.5" fill="none"
      stroke-linecap="round"/>`;
  };

  let content="",caption="";

  if(["dia","para","ferro"].includes(type)){
    const data={
      dia:["Диамагнетик","Мыс","Өріске қарсы",r],
      para:["Парамагнетик","Алюминий","Әлсіз бағыттас",b],
      ferro:["Ферромагнетик","Темір","Күшті магниттелу",g]
    }[type];

    caption=data[0]+" — магниттік жауаптың шартты моделі";

    content=rect(20,40,400,200,"#e3f2ff");

    content+=arrow(50,25,390,25,b);
    content+=txt(220,17,"Сыртқы өріс B",b,16);

    for(let i=0;i<24;i++){
      const x=48+(i%6)*67;
      const y=65+Math.floor(i/6)*49;

      const direction=type==="dia"?-1:
        type==="ferro"?1:
        i%3===0?-1:1;

      content+=`<circle cx="${x}" cy="${y}" r="15"
        fill="white" stroke="#bad5e8"/>`;

      content+=arrow(x-direction*11,y,
        x+direction*11,y,data[3]);
    }

    content+=txt(220,260,data[1]+" · "+data[2],data[3],21);

  }else if(type==="domains"||type==="aligned"||type==="curie"){
    const aligned=type==="aligned"||option===1;
    caption=type==="curie"?
      "Магниттік реттелудің температураға тәуелді моделі":
      "Магниттік домендердің бағдарлануы";

    content=rect(20,20,400,220,"#deedfa");

    const angles=[0,90,180,270,45,135,225,315];

    for(let i=0;i<20;i++){
      const x=25+(i%5)*78;
      const y=25+Math.floor(i/5)*52;
      const a=(aligned?0:angles[(i*3)%8])*Math.PI/180;

      content+=rect(x,y,73,47,aligned?"#c8edda":"#ffffff");

      const cx=x+36,cy=y+23;
      content+=arrow(cx-20*Math.cos(a),cy-20*Math.sin(a),
        cx+20*Math.cos(a),cy+20*Math.sin(a),
        aligned?g:[b,r,g][i%3]);
    }

    content+=txt(220,266,aligned?
      "Реттелген магниттік моменттер":
      "Әртүрлі бағытталған моменттер",aligned?g:b,18);

  }else if(type==="atom"){
    caption="Атомның магниттік моментінің шартты белгісі";

    content=`
      <ellipse cx="220" cy="130" rx="115" ry="60"
        fill="none" stroke="${b}" stroke-width="2"/>
      <ellipse cx="220" cy="130" rx="60" ry="115"
        fill="none" stroke="${b}" stroke-width="2"
        transform="rotate(40 220 130)"/>
      <circle cx="220" cy="130" r="30" fill="${r}"/>
      <circle cx="335" cy="130" r="12" fill="${b}"/>
      ${arrow(220,125,220,35,g)}
      ${txt(270,45,"Магниттік момент",g,17)}
      ${txt(220,270,"Шартты атомдық модель",k,20)}`;

  }else if(type==="saturation"||type==="temperature"){
    const sat=type==="saturation";
    caption=sat?"Магниттік қанығудың сапалық графигі":
      "Өздігінен магниттелудің сапалық графигі";

    content=`
      <path d="M45 20 V230 H415" stroke="${k}"
        stroke-width="2.5" fill="none"/>
      ${[65,110,155,200].map(y=>
        `<path d="M45 ${y} H410" stroke="#c5dce9"
          stroke-dasharray="5 5"/>`).join("")}
      ${txt(25,30,"M",k,20)}
      ${sat?`
        <path d="M45 230 C95 60,150 55,240 45 S350 40,410 40"
          stroke="${b}" stroke-width="5" fill="none"/>
        ${txt(275,28,"Қанығу",g,20)}
        ${txt(410,255,"H",k,20)}
      `:`
        <path d="M45 40 C190 45,260 75,310 230 H410"
          stroke="${r}" stroke-width="5" fill="none"/>
        <path d="M310 30 V230" stroke="${g}"
          stroke-width="2" stroke-dasharray="6 4"/>
        ${txt(310,255,"Tс",g,20)}
        ${txt(410,255,"T",k,20)}
      `}`;

  }else if(type==="hysteresis"){
    caption="Магниттік гистерезистің шартты қисығы";

    content=`
      <path d="M20 140 H420 M220 15 V265"
        stroke="${k}" stroke-width="2"/>
      <path d="M45 230 C160 230,240 215,285 110
        S355 45,395 50
        C280 50,200 65,155 170 S85 235,45 230 Z"
        fill="#087dcc14" stroke="${b}" stroke-width="4"/>
      ${txt(409,130,"H",k,20)}
      ${txt(240,25,"M",k,20)}
      ${txt(110,45,"Қалдық",r,18)}
      ${txt(110,66,"магниттелу",r,18)}`;

  }else if(["chi","permeability","formula"].includes(type)){
    caption="Сызықтық ортаның магниттік шамалары";

    content=`
      ${rect(20,30,400,220,"#e2f2ff")}
      ${txt(220,90,type==="chi"?"χ = M / H":"μᵣ = 1 + χ",b,38)}
      ${txt(220,150,"M = χH",g,35)}
      ${txt(220,207,"B = μ₀(H + M)",k,28)}`;

  }else{
    caption=type==="applications"?
      "Магниттік материалдардың қолданылуы":
      "Магниттік материалдардың үш негізгі түрі";

    const labels=type==="applications"?
      [["Трансформатор","Энергетика"],
       ["Датчик","Электроника"],
       ["Магнит","Техника"]]:
      [["Диамагнетик","Мыс"],
       ["Парамагнетик","Алюминий"],
       ["Ферромагнетик","Темір"]];

    content=labels.map(([a,c],i)=>{
      const x=10+i*145;
      return rect(x,30,138,220,["#ffe2e8","#dcefff","#d9f5e4"][i])+
        txt(x+69,90,["Ⅰ","Ⅱ","Ⅲ"][i],[r,b,g][i],45)+
        txt(x+69,155,a,k,15)+
        txt(x+69,200,c,[r,b,g][i],20);
    }).join("");
  }

  return `<div class="visual">
    <svg viewBox="0 0 440 280"
      xmlns="http://www.w3.org/2000/svg"
      font-family="Segoe UI,Arial,sans-serif">
      ${content}
    </svg>
    <small>${caption}</small>
  </div>`;
}

