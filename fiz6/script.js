/* eval ҚОЛДАНБАЙ ЕСЕПТЕУ */

function evaluateMath(source){
  const s=source.replace(/\s+/g,"");

  if(!s||s.length>500) throw Error("Қате");

  const t=s.match(
    /(?:\d+(?:\.\d*)?|\.\d+)(?:e[+-]?\d+)?|[a-z]+|[+\-*/^()]/gi
  )||[];

  if(t.join("")!==s) throw Error("Қате таңба");

  let p=0;

  function sum(){
    let x=product();

    while(t[p]==="+"||t[p]==="-"){
      const op=t[p++],y=product();
      x=op==="+"?x+y:x-y;
    }

    return x;
  }

  function product(){
    let x=unary();

    while(t[p]==="*"||t[p]==="/"){
      const op=t[p++],y=unary();

      if(op==="/"&&y===0) throw Error("Нөлге бөлу");

      x=op==="*"?x*y:x/y;
    }

    return x;
  }

  function unary(){
    if(t[p]==="+"){p++;return unary();}
    if(t[p]==="-"){p++;return -unary();}
    return power();
  }

  function power(){
    let x=atom();

    if(t[p]==="^"){
      p++;
      x=x**unary();
    }

    return x;
  }

  function atom(){
    const k=t[p++];

    if(k===undefined) throw Error("Өрнек толық емес");
    if(/^(?:\d|\.)/.test(k)) return Number(k);
    if(k==="pi") return Math.PI;

    if(k==="("){
      const x=sum();

      if(t[p++]!==")") throw Error("Жақша");

      return x;
    }

    const rad=x=>degree?x*Math.PI/180:x;

    const funcs={
      sin:x=>Math.sin(rad(x)),
      cos:x=>Math.cos(rad(x)),
      tan:x=>{
        if(Math.abs(Math.cos(rad(x)))<1e-12) throw Error("Анықталмаған");
        return Math.tan(rad(x));
      },
      ctg:x=>{
        if(Math.abs(Math.sin(rad(x)))<1e-12) throw Error("Анықталмаған");
        return 1/Math.tan(rad(x));
      },
      sqrt:Math.sqrt,
      ln:Math.log,
      log:Math.log10
    };

    if(Object.hasOwn(funcs,k)){
      if(t[p++]!=="(") throw Error("Жақша");

      const x=sum();

      if(t[p++]!==")") throw Error("Жақша");

      return funcs[k](x);
    }

    throw Error("Қате өрнек");
  }

  const result=sum();

  if(p!==t.length||!Number.isFinite(result))
    throw Error("Қате");

  return result;
}

