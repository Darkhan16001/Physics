const duration=80*60;

let elapsed=0;
let started=0;
let running=false;

function timerSeconds(){
  return Math.min(duration,Math.max(0,Math.floor(
    elapsed+(running?(Date.now()-started)/1000:0)
  )));
}

function updateTimer(){
  const remaining=duration-timerSeconds();

  $("timer").textContent=
    String(Math.floor(remaining/60)).padStart(2,"0")+":"+
    String(remaining%60).padStart(2,"0");

  $("timer").style.color=
    remaining<=300?"#d63a50":"#16874e";

  if(remaining===0){
    elapsed=duration;
    running=false;
  }

  $("timerBtn").textContent=running?"Тоқтату":"Бастау";
  $("timerBtn").disabled=remaining===0;
}

function startTimer(){
  if(running||elapsed>=duration) return;

  started=Date.now();
  running=true;

  updateTimer();
}

function toggleTimer(){
  if(running){
    elapsed=Math.min(
      duration,elapsed+(Date.now()-started)/1000
    );

    running=false;
  }else{
    startTimer();
  }

  updateTimer();
}

function resetTimer(){
  if(!confirm("Таймерді 80 минутқа қайтарамыз ба?")) return;

  elapsed=0;
  started=0;
  running=false;

  updateTimer();
}

