function diagram(type){
  const b="#087dcc",r="#d63a50",g="#16874e",k="#38576e";

  const txt=(x,y,s,c=k,size=18)=>
    `<text x="${x}" y="${y}" text-anchor="middle"
      fill="${c}" font-size="${size}" font-weight="600">${s}</text>`;

  const rect=(x,y,w,h,c)=>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}"
      rx="12" fill="${c}"/>`;

  const particle=(x,y,s,c,rad=17)=>`
    <circle cx="${x}" cy="${y}" r="${rad}" fill="${c}"/>
    ${txt(x,y+6,s,"white",17)}`;

  const arrow=(x,y,X,Y,c=b)=>{
    const a=Math.atan2(Y-y,X-x);

    return `<path d="M${x} ${y} L${X} ${Y}
      L${X-12*Math.cos(a-.5)} ${Y-12*Math.sin(a-.5)}
      M${X} ${Y}
      L${X-12*Math.cos(a+.5)} ${Y-12*Math.sin(a+.5)}"
      stroke="${c}" stroke-width="4" fill="none"/>`;
  };

  let content="",caption="";

  if(["gas","plasma","direction","vacuum"].includes(type)){
    caption={
      gas:"Газдағы зарядталған және бейтарап бөлшектер",
      plasma:"Плазманың шартты бөлшектік моделі",
      direction:"Зарядтардың бағытталған қозғалысы",
      vacuum:"Вакуумдағы электрондар ағыны"
    }[type];

    content=rect(15,20,410,220,
      type==="plasma"?"#203d72":"#e1f2ff");

    for(let i=0;i<18;i++){
      const x=43+(i*83)%350;
      const y=45+(i*57)%165;
      const s=type==="vacuum"?"−":i%3===0?"○":i%3===1?"+":"−";
      const c=s==="+"?r:s==="−"?b:"#91a9bb";

      content+=particle(x,y,s,c,14);

      if(type==="direction"&&s!=="○"){
        content+=arrow(x,y+20,x+(s==="+"?24:-24),y+20,c);
      }
    }

    content+=txt(220,266,
      type==="vacuum"?"Электрондар":"○ Бейтарап  ·  + Ион  ·  − Электрон",k,16);

  }else if(type==="ion"||type==="recombination"){
    const reverse=type==="recombination";
    caption=reverse?"Рекомбинация":"Иондалу";

    content=`
      ${rect(15,45,160,165,"#dcefff")}
      ${rect(265,45,160,165,"#e5f8ed")}
      ${reverse?
        particle(65,120,"+",r,27)+particle(130,120,"−",b,16):
        particle(95,120,"A","#91a9bb",35)}
      ${arrow(185,125,255,125,g)}
      ${reverse?
        particle(345,120,"A","#91a9bb",35):
        particle(310,120,"+",r,27)+particle(380,120,"−",b,16)}
      ${txt(95,245,reverse?"A⁺ + e⁻":"A",b,22)}
      ${txt(345,245,reverse?"A":"A⁺ + e⁻",g,22)}`;

  }else if(type==="energy"||type==="electron"){
    caption=type==="energy"?"Энергияның өлшем бірліктері":
      "Электронның физикалық шамалары";

    content=`
      ${rect(20,25,400,220,"#e2f1ff")}
      ${particle(220,90,"−",b,37)}
      ${txt(220,165,type==="energy"?"1 эВ = 1,6 × 10⁻¹⁹ Дж":"e = 1,6 × 10⁻¹⁹ Кл",b,23)}
      ${txt(220,208,type==="energy"?"Электрон-вольт":"mₑ = 9,11 × 10⁻³¹ кг",g,22)}`;

  }else if(type==="decay"){
    caption="Заряд тасымалдаушылар санының шартты азаюы";

    content=`
      <path d="M45 20 V225 H410" stroke="${k}" stroke-width="3" fill="none"/>
      <path d="M45 45 C130 55,150 150,220 180 S330 218,400 220"
        stroke="${r}" stroke-width="5" fill="none"/>
      ${txt(20,30,"N")}
      ${txt(415,250,"t")}
      ${txt(240,80,"Рекомбинация",r,23)}
      ${txt(220,265,"Уақыт",b,18)}`;

  }else if(type==="types"||type==="glow"){
    caption="Газ разрядтарының шартты көріністері";

    content=`
      ${rect(15,20,195,110,"#203458")}
      ${rect(230,20,195,110,"#203458")}
      ${rect(15,145,195,110,"#203458")}
      ${rect(230,145,195,110,"#203458")}
      <ellipse cx="112" cy="62" rx="58" ry="22" fill="#b58df8" opacity=".8"/>
      <path d="M245 65 L290 44 L320 82 L355 45 L407 65"
        fill="none" stroke="#c9eaff" stroke-width="5"/>
      <path d="M40 205 Q110 148 185 205"
        fill="none" stroke="#ffdb83" stroke-width="9"/>
      <circle cx="328" cy="188" r="27" fill="#86bfff" opacity=".4"/>
      <circle cx="328" cy="188" r="13" fill="#b3ddff"/>
      ${txt(112,112,"Солғын","white")}
      ${txt(328,112,"Ұшқындық","white")}
      ${txt(112,240,"Доғалық","white")}
      ${txt(328,240,"Тәждік","white")}`;

  }else if(type==="emission"){
    caption="Электрондық эмиссияның бөлшектік моделі";

    content=`
      ${rect(30,175,380,65,"#9bb9cf")}
      ${[70,130,190,250,310,370].map(x=>
        particle(x,205,"−",b,12)).join("")}
      ${[100,180,260,340].map(x=>
        particle(x,85,"−",b,13)+arrow(x,160,x,110,g)).join("")}
      ${txt(220,35,"Еркін электрондар",b,22)}
      ${txt(220,265,"Материал беті",k,19)}`;

  }else if(type==="screen"){
    caption="Электрондар шоғы мен экранның шартты көрінісі";

    content=`
      ${rect(15,30,410,220,"#203458")}
      ${[50,90,130,170,210,250,290].map(x=>
        particle(x,125,"−","#47b8ff",10)).join("")}
      <rect x="365" y="60" width="30" height="130"
        rx="12" fill="#7ed7ae"/>
      <circle cx="380" cy="125" r="12" fill="#f2ffb6"/>
      ${txt(190,72,"Электрондар шоғы","white",19)}
      ${txt(380,220,"Экран","white",16)}
      ${txt(220,270,"Жарық нүктесінің пайда болуы",g,17)}`;

  }else{
    caption="Әртүрлі ортадағы заряд тасымалдаушылар";

    const labels=[
      ["Металл","Электрондар"],
      ["Электролит","Иондар"],
      ["Газ","Иондар, электрондар"],
      ["Вакуум","Электрондар шоғы"]
    ];

    content=labels.map(([a,c],i)=>{
      const x=15+(i%2)*210;
      const y=15+Math.floor(i/2)*130;

      return rect(x,y,200,120,i%2?"#e5f8ed":"#dcefff")+
        txt(x+100,y+42,a,b,23)+txt(x+100,y+82,c,k,16);
    }).join("");
  }

  return `<div class="visual">
    <svg viewBox="0 0 440 280"
      xmlns="http://www.w3.org/2000/svg"
      font-family="Segoe UI,Arial,sans-serif">
      ${content}
    </svg>
    <small>${caption}</small>
  </div>`;
}

